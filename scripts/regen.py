"""Rebuild the generated views of a PhysicsIntern workspace.

Writes INDEX.md (one line per item, with its computed status, evidence and
the needs re-check flag) and research_log.md (the same content grouped as
Open Questions, Working Claims, Established Results and Dead Ends, followed by
the session reports). Both files are git-ignored and never edited by hand, so
running this twice gives identical files.

Usage: uv run .physics-intern/scripts/regen.py [--root PATH] [--quiet]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from cards import Workspace, find_root, natural_key  # noqa: E402

HEADER = "<!-- Generated by .physics-intern/scripts/regen.py from the workspace files. Do not edit. -->"
CARD_ID_RE = re.compile(r"\b(?:CL|Q|DE)-[A-Za-z0-9._-]+\b")


def one_line(text: str, limit: int = 0) -> str:
    text = " ".join(str(text).split())
    if limit and len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text


def review_label(review) -> str:
    """Short name of a review: `R-S3-2` for an agent review, `R-alice-…` for a human one."""
    label = review.id.split("_", 1)[1] if "_R-" in review.id else review.id
    if review.by_human:
        label += f" by {review.by.get('user', '?')}"
    return label


def evidence_parts(ws: Workspace, card_id: str) -> list[str]:
    parts = []
    for item in ws.evidence(card_id):
        if item.verification is not None:
            r = item.verification
            parts.append(f"verification {review_label(r)} {r.verdict}")
            continue
        reviews = "; ".join(f"{review_label(r)} {r.verdict}" for r in item.reviews) or "no review yet"
        parts.append(f"{item.artefact} [{reviews}]")
    return parts


def proposed_promotions(ws: Workspace) -> dict[str, list[str]]:
    """Map card ID -> sessions whose report proposes promoting it."""
    proposed: dict[str, list[str]] = {}
    for session in ws.sessions.values():
        text = session.report_sections.get("Proposed promotions", "")
        for card_id in sorted(set(CARD_ID_RE.findall(text)), key=natural_key):
            if card_id in ws.cards:
                proposed.setdefault(card_id, []).append(session.id)
    return proposed


def reaction_text(ws: Workspace, target: str) -> str:
    counts: dict[str, int] = {}
    for reaction in ws.current_reactions(target):
        counts[reaction.value] = counts.get(reaction.value, 0) + 1
    return ", ".join(f"{value} ×{n}" for value, n in sorted(counts.items()))


def status_text(ws: Workspace, card_id: str) -> str:
    status = ws.status(card_id)
    if status == "refuted":
        return f"refuted by {', '.join(ws.refuters(card_id))}"
    if status == "revised":
        return f"revised by {', '.join(ws.revisers(card_id))}"
    if status == "answered":
        return f"answered by {', '.join(ws.answerers(card_id))}"
    return status


def recheck_text(ws: Workspace, card_id: str) -> str:
    causes = ws.needs_recheck(card_id)
    if not causes:
        return ""
    return "needs re-check (" + ", ".join(f"{c} {ws.status(c)}" for c in causes) + ")"


def card_line(ws: Workspace, card, proposals: dict[str, list[str]]) -> str:
    fields = [f"**{card.id}**", status_text(ws, card.id)]
    recheck = recheck_text(ws, card.id)
    if recheck:
        fields.append(recheck)
    line = "- " + " · ".join(fields) + " — " + one_line(card.statement, 220)
    extras = []
    if card.kind == "claim":
        evidence = evidence_parts(ws, card.id)
        extras.append("evidence: " + (", ".join(evidence) if evidence else "none"))
        if card.id in proposals and ws.status(card.id) == "working":
            extras.append("promotion proposed in " + ", ".join(proposals[card.id]))
    if card.refutes:
        extras.append("refutes " + ", ".join(card.refutes))
    if card.supersedes:
        extras.append("supersedes " + ", ".join(card.supersedes))
    if card.answers:
        extras.append("answers " + ", ".join(card.answers))
    if card.depends_on:
        extras.append("depends on " + ", ".join(card.depends_on))
    reactions = reaction_text(ws, card.id)
    if reactions:
        extras.append("reactions: " + reactions)
    if card.produced_by.get("kind") == "human":
        extras.append(f"written by {card.produced_by.get('user', '?')}")
    return line + ("" if not extras else " — " + " — ".join(extras))


def render_index(ws: Workspace) -> str:
    proposals = proposed_promotions(ws)
    out = ["# Index", "", HEADER, ""]

    claims = ws.sorted_cards("claim")
    order = {"working": 0, "established": 1, "revised": 2, "refuted": 3}
    out += ["## Claims", ""]
    if claims:
        for status in order:
            for card in claims:
                if ws.status(card.id) == status:
                    out.append(card_line(ws, card, proposals))
    else:
        out.append("(none yet)")
    out.append("")

    questions = ws.sorted_cards("question")
    out += ["## Questions", ""]
    if questions:
        for status in ("open", "answered"):
            for card in questions:
                if ws.status(card.id) == status:
                    out.append(card_line(ws, card, proposals))
    else:
        out.append("(none yet)")
    out.append("")

    out += ["## Dead ends", ""]
    dead_ends = ws.sorted_cards("dead-end")
    out += [card_line(ws, c, proposals) for c in dead_ends] or ["(none yet)"]
    out.append("")

    out += ["## Artefacts", ""]
    if ws.artefacts:
        for art_id in sorted(ws.artefacts, key=natural_key):
            art = ws.artefacts[art_id]
            reviews = "; ".join(f"{review_label(r)} {r.verdict}" for r in ws.reviews_of(art_id)) or "no review yet"
            supports = ", ".join(art.supports) or "nothing"
            out.append(f"- **{art_id}** ({art.kind}, `{art.path}`) — supports {supports} — reviews: {reviews}")
    else:
        out.append("(none yet)")
    out.append("")

    out += ["## Literature", ""]
    if ws.papers:
        for paper_id in sorted(ws.papers, key=natural_key):
            paper = ws.papers[paper_id]
            year = f" ({paper.year})" if paper.year else ""
            triage = reaction_text(ws, paper_id)
            out.append(
                f"- **{paper_id}** — {one_line(paper.title, 160)}{year}" + (f" — triage: {triage}" if triage else "")
            )
    else:
        out.append("(no paper cards yet)")
    if ws.surveys:
        out.append("")
        out.append("Survey summaries: " + ", ".join(f"`literature/{s}.md`" for s in ws.surveys))
    out.append("")

    out += ["## Sessions", ""]
    if ws.sessions:
        for session in sorted(ws.sessions.values(), key=lambda s: s.number):
            out.append(session_line(session))
    else:
        out.append("(no sessions yet)")
    out.append("")
    return "\n".join(out)


def session_line(session) -> str:
    goal = one_line(session.goal, 160) or "(no brief yet)"
    if session.report:
        state = f"stopped: {one_line(session.report.get('stop_reason', '?'))}"
    else:
        state = "no report yet"
    return f"- **{session.id}** — {goal} — {state}"


def claim_entry(ws: Workspace, card, proposals) -> list[str]:
    lines = [f"- {card.id}: {one_line(card.statement)}"]
    if card.kind == "claim":
        evidence = evidence_parts(ws, card.id)
        lines.append("  - evidence: " + ("; ".join(evidence) if evidence else "none yet"))
    if card.depends_on:
        lines.append("  - depends on: " + ", ".join(card.depends_on))
    recheck = recheck_text(ws, card.id)
    if recheck:
        lines.append("  - " + recheck)
    for label, ids in (("supersedes", card.supersedes), ("refutes", card.refutes), ("answers", card.answers)):
        if ids:
            lines.append(f"  - {label}: " + ", ".join(ids))
    status = ws.status(card.id)
    if status not in ("working", "established", "open", "dead-end"):
        lines.append(f"  - status: {status_text(ws, card.id)}")
    for promotion in ws.promotions_of(card.id):
        if ws.promotion_is_valid(promotion):
            who = promotion.by.get("user") or f"agent ({promotion.by.get('model', '?')})"
            history = "" if status == "established" else f" (kept as history; the card is now {status})"
            lines.append(f"  - promoted by {who} on {promotion.date[:10]}{history}")
    if card.id in proposals and status == "working":
        lines.append("  - promotion proposed in: " + ", ".join(proposals[card.id]))
    produced = card.produced_by
    if produced.get("kind") == "human":
        origin = f"written by {produced.get('user', '?')}"
    elif produced:
        origin = f"agent {produced.get('model', '?')}, operator {produced.get('operator', '?')}"
    else:
        origin = "author not recorded"
    lines.append(f"  - origin: {origin}" + (f", session {card.session}" if card.session else ""))
    for reaction in ws.current_reactions(card.id):
        comment = f': "{one_line(reaction.comment, 160)}"' if reaction.comment else ""
        lines.append(f"  - reaction: {reaction.value} by {reaction.user}{comment}")
    return lines


def render_log(ws: Workspace) -> str:
    proposals = proposed_promotions(ws)
    out = ["# Research log", "", HEADER, ""]
    out.append("Conventions are in `conventions.md`; the question, the definition of done and the sanity checks are in `problem.md`.")
    out.append("")

    def section(title: str, cards: list) -> None:
        out.extend([f"## {title}", ""])
        if not cards:
            out.extend(["(none)", ""])
            return
        for card in cards:
            out.extend(claim_entry(ws, card, proposals))
        out.append("")

    section("Open Questions", [c for c in ws.sorted_cards("question") if ws.status(c.id) == "open"])
    section("Working Claims", [c for c in ws.sorted_cards("claim") if ws.status(c.id) == "working"])
    section("Established Results", [c for c in ws.sorted_cards("claim") if ws.status(c.id) == "established"])
    dead = ws.sorted_cards("dead-end") + [
        c for c in ws.sorted_cards("claim") if ws.status(c.id) in ("refuted", "revised")
    ]
    section("Dead Ends", dead)
    section("Answered Questions", [c for c in ws.sorted_cards("question") if ws.status(c.id) == "answered"])

    out.extend(["## Sessions", ""])
    if not ws.sessions:
        out.extend(["(none)", ""])
    for session in sorted(ws.sessions.values(), key=lambda s: s.number):
        out.append(session_line(session))
        for heading in ("Found", "Refuted", "Left open", "Proposed plan changes", "Needs a human decision"):
            text = session.report_sections.get(heading, "").strip()
            if text and text.lower() not in ("(none)", "none", "- (none)"):
                out.append(f"  - {heading}:")
                out.extend("    " + line for line in text.splitlines() if line.strip())
    out.append("")
    return "\n".join(out)


def regenerate(root: Path) -> Workspace:
    ws = Workspace(root)
    (root / "INDEX.md").write_text(render_index(ws), encoding="utf-8")
    (root / "research_log.md").write_text(render_log(ws), encoding="utf-8")
    return ws


def summary(ws: Workspace) -> str:
    claims = ws.sorted_cards("claim")
    counts: dict[str, int] = {}
    for card in claims:
        counts[ws.status(card.id)] = counts.get(ws.status(card.id), 0) + 1
    recheck = sum(1 for c in ws.cards if ws.needs_recheck(c))
    open_q = sum(1 for c in ws.sorted_cards("question") if ws.status(c.id) == "open")
    parts = [f"{n} {s}" for s, n in sorted(counts.items())]
    return (
        f"{len(claims)} claims ({', '.join(parts) or 'none'}), {open_q} open questions, "
        f"{recheck} cards needing a re-check, {len(ws.artefacts)} artefacts, {len(ws.papers)} paper cards"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, help="workspace root (default: found from the current folder)")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve() if args.root else find_root()
    ws = regenerate(root)
    for problem in ws.problems:
        print(problem, file=sys.stderr)
    if not args.quiet:
        print(f"Wrote INDEX.md and research_log.md: {summary(ws)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
